// Build supabase/seed-insights.sql: one `product_insights` row per catalog product,
// derived deterministically (no AI, no network) by lib/decision/derive.ts from each
// product's title, bullets, rating, review volume and price rank in its category.
// `supabase db reset` loads it after seed.sql (see [db.seed] sql_paths in config.toml),
// so the decision UI works with no GEMINI_API_KEY.
// Run: node scripts/build-insights.mjs   (then: npx supabase db reset)
// Node ≥ 22.18 strips the TypeScript types from the imported lib/decision files.
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';
import { decisionConfig } from '../lib/decision/attributes.ts';
import { deriveInsight, pricePercentiles } from '../lib/decision/derive.ts';

const ROOT = join(dirname(fileURLToPath(import.meta.url)), '..');
const SEED_DIR = join(ROOT, 'supabase', 'seed');

const q = (v) => (v === undefined || v === null ? 'null' : `'${String(v).replace(/'/g, "''")}'`);
const arr = (list) => `array[${list.map(q).join(', ')}]::text[]`;
const js = (v) => `${q(JSON.stringify(v))}::jsonb`;

/** Every product's rules insight, in catalog order. */
export async function buildInsights() {
  const us = JSON.parse(await readFile(join(SEED_DIR, 'catalog-us.json'), 'utf8'));
  const inn = JSON.parse(await readFile(join(SEED_DIR, 'catalog-in.json'), 'utf8'));
  const catalog = [
    ...us.products.map((p) => ({ ...p, market: 'US' })),
    ...inn.products.map((p) => ({ ...p, market: 'IN' })),
  ];
  const pct = pricePercentiles(catalog);
  return catalog.map((p) => deriveInsight(p, decisionConfig(p.category), { pricePercentile: pct.get(p.id) ?? 0.5 }));
}

async function main() {
  const insights = await buildInsights();
  const rows = insights.map((i) =>
    [q(i.productId), js(i.scores), arr(i.pros), arr(i.cons), q(i.bestFor), q(i.summary), js(i.praised), js(i.criticized), q('rules')].join(', '),
  );
  const chunks = [];
  for (let k = 0; k < rows.length; k += 200) {
    chunks.push(
      'insert into public.product_insights (product_id, scores, pros, cons, best_for, summary, praised, criticized, source) values\n  ' +
        rows.slice(k, k + 200).map((r) => `(${r})`).join(',\n  ') +
        '\non conflict (product_id) do nothing;\n',
    );
  }
  const sql = [
    '-- AUTO-GENERATED by scripts/build-insights.mjs from supabase/seed/catalog-*.json — do not edit by hand.',
    '-- Loaded by `supabase db reset` after seed.sql.',
    '',
    ...chunks,
  ].join('\n');
  await writeFile(join(ROOT, 'supabase', 'seed-insights.sql'), sql);
  console.log(`wrote supabase/seed-insights.sql — ${insights.length} product insights`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
